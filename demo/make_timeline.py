"""Turn narration lengths, footage chapters and spoken-word times into the video project's timeline.ts.

    python demo/make_timeline.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import soundfile as sf

sys.path.insert(0, str(Path(__file__).parent))
from video_script import PUBLIC, PROJECT, SCENES  # noqa: E402

FPS = 30
CUES = {
    "aws": {"bedrock": "bedrock", "cognito": "cognito", "ec2": "ec2", "dynamodb": "dynamodb",
            "eventbridge": "eventbridge", "sns": "sns", "transcribe": "transcribe", "textract": "textract"},
    "future": {"photo": "photo", "family": "family", "reminders": "reminders"},
}


def words(path: Path) -> list[tuple[str, int]]:
    return [(re.sub(r"[^a-z0-9]", "", w["text"].lower()), w["startMs"]) for w in json.loads(path.read_text())]


def main() -> None:
    lengths = json.loads((PUBLIC / "audio" / "lengths.json").read_text())
    footage = json.loads((PUBLIC / "footage" / "timeline.json").read_text())
    alexa_len = sf.info(PUBLIC / "audio" / "alexa-reminder.wav").duration
    rows, total = [], 0
    for index, (scene_id, kind, _text) in enumerate(SCENES, start=1):
        audio = f"audio/scenes/{index:02d}-{scene_id}.wav"
        row = {"id": scene_id, "kind": kind, "audio": audio}
        narration = lengths[scene_id]
        if kind == "app":
            chapter = footage["chapters"][scene_id]
            row["chapter"] = chapter
            frames = round((chapter["end"] - chapter["start"]) * FPS)
        elif kind == "echo":
            row["narrationDelay"] = round(44 + alexa_len * FPS + 14)
            frames = row["narrationDelay"] + round((narration + 1.3) * FPS)
        elif kind == "title":
            frames = round((narration + 1.8) * FPS)
        elif kind == "close":
            frames = round((narration + 2.2) * FPS)
        else:
            frames = round((narration + 1.3) * FPS)
        row["frames"] = frames
        if scene_id in CUES:
            spoken = words(PUBLIC / f"{audio[:-4]}.captions.json")
            cues = {}
            for key, needle in CUES[scene_id].items():
                hit = next((ms for token, ms in spoken if needle in token), None)
                if hit is not None:
                    cues[key] = round(hit / 1000 * FPS)
            row["cues"] = cues
        rows.append(row)
        total += frames
    alexa = {
        "text": footage["alexa"]["text"],
        "offsetFrames": round(footage["alexa"]["offset"] * FPS),
        "audio": "audio/alexa-reminder.wav",
    }
    source = (
        "// Generated by demo/make_timeline.py. Do not edit by hand.\n"
        "export type SceneCfg = {\n  id: string; kind: string; frames: number; audio: string;\n"
        "  chapter?: { start: number; end: number }; cues?: Record<string, number>; narrationDelay?: number;\n};\n"
        f"export const FPS = {FPS};\n"
        f"export const TOTAL_FRAMES = {total};\n"
        f"export const SCENES: SceneCfg[] = {json.dumps(rows, indent=2)};\n"
        f"export const ALEXA = {json.dumps(alexa, indent=2)};\n"
    )
    target = PROJECT / "src" / "config" / "timeline.ts"
    target.write_text(source)
    start = 0
    for row in rows:
        print(f"  {row['id']:9s} starts at frame {start:5d} ({start / FPS:6.1f}s), {row['frames'] / FPS:5.1f}s long")
        start += row["frames"]
    print(f"{total / FPS:.1f}s total -> {target}")


if __name__ == "__main__":
    main()
